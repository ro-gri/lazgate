package protogen

import (
	"bytes"
	"embed"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"text/template"
)

//go:embed templates/*.tmpl
var templates embed.FS

const generatedHeader = "// Code generated by agent-proto-gen; DO NOT EDIT.\n\n"

type Spec struct {
	Package          string `json:"package"`
	ProtoPackage     string `json:"proto_package"`
	GoPackage        string `json:"go_package"`
	CredentialImport string `json:"credential_import"`
}

type templateSpec struct {
	Package          string
	ProtoPackage     string
	GoPackage        string
	CredentialImport string
}

func GenerateFiles(specPath, protoOutPath, goOutPath string) error {
	spec, err := LoadSpec(specPath)
	if err != nil {
		return err
	}
	if protoOutPath == "" && goOutPath == "" {
		return fmt.Errorf("at least one output path is required")
	}
	outputs := []struct {
		path     string
		generate func(Spec) ([]byte, error)
	}{
		{path: protoOutPath, generate: Generate},
		{path: goOutPath, generate: GenerateManifestBuilder},
	}
	for _, output := range outputs {
		if output.path == "" {
			continue
		}
		content, err := output.generate(spec)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(output.path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(output.path, content, 0644); err != nil {
			return err
		}
	}
	return nil
}

func LoadSpec(path string) (Spec, error) {
	if path == "" {
		return Spec{}, fmt.Errorf("spec path is required")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return Spec{}, err
	}
	var spec Spec
	if err := json.Unmarshal(raw, &spec); err != nil {
		return Spec{}, err
	}
	return spec, ValidateSpec(spec)
}

func Generate(spec Spec) ([]byte, error) {
	out, err := generateTemplate(spec, "templates/agent.proto.tmpl")
	if err != nil {
		return nil, err
	}
	return append([]byte(generatedHeader), out...), nil
}

func GenerateManifestBuilder(spec Spec) ([]byte, error) {
	out, err := generateTemplate(spec, "templates/manifest_builder.go.tmpl")
	if err != nil {
		return nil, err
	}
	return format.Source(append([]byte(generatedHeader), out...))
}

func generateTemplate(spec Spec, templatePath string) ([]byte, error) {
	if err := ValidateSpec(spec); err != nil {
		return nil, err
	}
	rawTemplate, err := templates.ReadFile(templatePath)
	if err != nil {
		return nil, err
	}
	tmpl, err := template.New(filepath.Base(templatePath)).Parse(string(rawTemplate))
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	if err := tmpl.Execute(&out, buildTemplateSpec(spec)); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

var packageNamePattern = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

func ValidateSpec(spec Spec) error {
	if spec.Package == "" {
		return fmt.Errorf("package is required")
	}
	if !packageNamePattern.MatchString(spec.Package) {
		return fmt.Errorf("package %q must match %s", spec.Package, packageNamePattern.String())
	}
	return nil
}

func buildTemplateSpec(spec Spec) templateSpec {
	protoPackage := spec.ProtoPackage
	if protoPackage == "" {
		protoPackage = "laz.nodeproto." + spec.Package
	}
	goPackage := spec.GoPackage
	if goPackage == "" {
		goPackage = fmt.Sprintf("laz/generated/nodeproto/%s", spec.Package)
	}
	credentialImport := spec.CredentialImport
	if credentialImport == "" {
		credentialImport = fmt.Sprintf("proto/%s.proto", spec.Package)
	}
	return templateSpec{
		Package:          spec.Package,
		ProtoPackage:     protoPackage,
		GoPackage:        goPackage,
		CredentialImport: credentialImport,
	}
}
